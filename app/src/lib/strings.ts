export type Key = keyof typeof en;
type Table = Record<Key, string>;

const tables: Record<string, Table> = { en };
let currentLanguage = "en";

export function setLanguage(code: string): void {
  if (tables[code]) currentLanguage = code;
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = tables[currentLanguage][key] ?? en[key];
  const all = { app: APP_DISPLAY_NAME, ...vars };
  return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in all ? String(all[name as keyof typeof all]) : match));
}
